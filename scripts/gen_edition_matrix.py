#!/usr/bin/env python3
"""Write ui/src/lib/edition-matrix.gen.ts from app/core/editions.py.

The Billing tab compares the three plans a customer can buy. The UI cannot
import Python at runtime, so the plan matrix crosses the boundary as a committed
generated file, the way ui/src/routeTree.gen.ts does for routes.
tests/contract/test_edition_matrix_generated.py regenerates it and fails on any
difference, so a changed flag cannot reach the screen, or fail to, unnoticed.

    python scripts/gen_edition_matrix.py          # rewrite the file
    python scripts/gen_edition_matrix.py --check  # exit 1 if it is stale

editions.py is loaded by path: it is stdlib-only, so this runs on any Python
with no project dependencies installed.
"""

from __future__ import annotations

import argparse
import dataclasses
import importlib.util
import sys
from pathlib import Path
from types import ModuleType

REPO_ROOT = Path(__file__).resolve().parents[1]
EDITIONS_PY = REPO_ROOT / "app" / "core" / "editions.py"
OUTPUT = REPO_ROOT / "ui" / "src" / "lib" / "edition-matrix.gen.ts"

#: The plans on sale, cheapest first. "oss" is in _HOSTED only as a fallback
#: identity; nobody can buy it, so it has no column.
PLANS = ("free", "professional", "enterprise")


def load_editions(path: Path = EDITIONS_PY) -> ModuleType:
    """Import an editions.py from ``path`` without importing the app package."""
    name = f"_edition_matrix_source_{abs(hash(str(path)))}"
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    # dataclasses resolves string annotations through sys.modules.
    sys.modules[name] = module
    try:
        spec.loader.exec_module(module)
    finally:
        del sys.modules[name]
    return module


def render(editions: ModuleType) -> str:
    """The generated file's exact text for this editions module."""
    capabilities = [f.name for f in dataclasses.fields(editions.Capabilities)]
    lines = [
        "// GENERATED by scripts/gen_edition_matrix.py from app/core/editions.py.",
        "// Do not edit. Change the matrix, then run the script.",
        "",
        "export const EDITION_PLANS = [",
        *(f'  "{plan}",' for plan in PLANS),
        "] as const;",
        "",
        "export type EditionPlan = (typeof EDITION_PLANS)[number];",
        "",
        "export const EDITION_CAPABILITIES = [",
        *(f'  "{name}",' for name in capabilities),
        "] as const;",
        "",
        "export type EditionCapability = (typeof EDITION_CAPABILITIES)[number];",
        "",
        "/** Shipped on this line, or entitled but not shipped yet. */",
        'export type CapabilityStatus = "shipped" | "coming";',
        "",
        "export const EDITION_CAPABILITY_STATUS: Record<EditionCapability, CapabilityStatus> = {",
        *(f'  {name}: "{editions.CAPABILITY_STATUS[name]}",' for name in capabilities),
        "};",
        "",
        "export const EDITION_MATRIX: Record<EditionPlan, Record<EditionCapability, boolean>> = {",
    ]
    for plan in PLANS:
        granted = editions._HOSTED[plan]
        lines.append(f"  {plan}: {{")
        lines.extend(
            f"    {name}: {'true' if getattr(granted, name) else 'false'},"
            for name in capabilities
        )
        lines.append("  },")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the file is stale")
    parser.add_argument("--editions", type=Path, default=EDITIONS_PY, help=argparse.SUPPRESS)
    parser.add_argument("--output", type=Path, default=OUTPUT, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)

    text = render(load_editions(args.editions))
    if args.check:
        current = args.output.read_text(encoding="utf-8") if args.output.exists() else ""
        if current != text:
            print(f"{args.output} is stale: run python scripts/gen_edition_matrix.py", file=sys.stderr)
            return 1
        return 0
    args.output.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
