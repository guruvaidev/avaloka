"""The upload path must understand the workbook, not just open it.

This is the app-side half of the comprehension benchmark. The CLI's reader and
the upload path are two different implementations -- ``avaloka/io/loader.py``
has its own header scan, the upload path goes through
``file_handler/excel_connector.py`` and ``file_handler/table_shape.py`` -- and
they disagree on real files. The benchmark family in ``avaloka/benchmark/``
cannot grade this one, because ``avaloka`` must not import ``file_handler``
(the CLI ships without it), so the upload path is graded here.

Every fixture is generated by the same builders the benchmark uses, so the two
halves cannot drift onto different data.

These landed **red**. Each is a shape a person actually produced in a
spreadsheet, and the reader's answer differed from what is in the file. What
each one turned out to be, measured rather than guessed:

* ``year_columns_header`` -- a header of ``Region | 2021 | 2022 | 2023``
  became ``column_1 .. column_4``. ``_looks_like_a_label`` returns False for
  "2021" because the string parses as a number, so one label out of four
  failed the ``len(labels) < len(cells) * 0.7`` guard. Period columns are how
  every financial statement is laid out, so this is not an edge case.
* ``stacked_two_row_header`` -- **not** the numeric guard, which is what this
  docstring used to imply. ``Region | Sales | Sales | Cost | Cost`` is five
  labels out of five. It was rejected by the repeated-label guard ("a banded
  data row"), which cannot tell a group header from a banded record.
* ``merged_header_cells`` -- row 0 was accepted as the header and row 1, the
  half that names the columns under each merged cell, was never consulted.
* ``footnote_markers_on_labels`` -- ``*``/``(a)``/``†`` stayed glued to labels
  and the footnote block was read as data rows.
* ``second_table_below`` -- a second table under the first was read as more
  rows of the first.

Three of those are one defect: the header is two rows and the reader could
only answer with one index. ``table_shape.detect_header_rows`` returns a span.

**Still red, on purpose:** ``sec_financial_report`` and
``decoy_sheet_outweighs_the_answer``. ``_resolve_sheet`` picks the sheet with
the most rows, so on a 10-K it reads the balance sheet when the question is
about the income statement. Row count is a poor proxy for relevance, but the
reader does not have the question, and any rule that passes both of these
without it is a rule fitted to two fixtures: ``test_excel_sheet_selection``
pins the mirror image (small summary first, real data second). They stay
failing rather than skipped until sheet choice is made where the question is.
With the sheet named, the 10-K reads correctly
(``tests/test_spreadsheet_shape_assumptions.py``).

The point of writing them down as failures is that the suite scored 1.00 while
all of this was true.
"""

from __future__ import annotations

import re

import pandas as pd
import pytest

pytest.importorskip("openpyxl", reason="the workbook builders need openpyxl")

from avaloka.benchmark.datasets_spreadsheet import SPREADSHEET_DATASETS  # noqa: E402

#: The two shapes a name takes when the reader gave up on finding one:
#: pandas' own ``Unnamed: 3`` and ``table_shape``'s ``column_4``.
_PLACEHOLDER = re.compile(r"^(Unnamed:\s*\d+|column_\d+)$")


@pytest.fixture(scope="module")
def workbooks(tmp_path_factory):
    """Build every spreadsheet fixture once, read it through the upload path."""
    from file_handler.excel_connector import ExcelConnector
    base = tmp_path_factory.mktemp("workbooks")
    out = {}
    for name, (builder, truth) in SPREADSHEET_DATASETS.items():
        path = base / f"{name}.xlsx"
        builder(path)
        connector = ExcelConnector(str(path))
        out[name] = {
            "truth": truth,
            "frame": connector.load_dataframe(),
            "sheet": connector.selected_sheet,
            "report": connector.shape_report,
        }
    return out


def test_the_fixtures_actually_built(workbooks):
    """Without this, an empty fixture dict would make every check below pass."""
    assert len(workbooks) >= 10, f"only {len(workbooks)} workbooks built"
    for name, got in workbooks.items():
        assert not got["frame"].empty, f"{name} produced an empty frame"


@pytest.mark.parametrize("name", sorted(SPREADSHEET_DATASETS))
def test_no_column_comes_back_as_a_placeholder(name, workbooks):
    """A placeholder name is the symptom the user sees as 'Unnamed: 13'.

    It is not cosmetic: the profiler types the column off it, the planner is
    handed it as the schema, and the insight text then names it in a real
    sentence about a column that does not exist.
    """
    frame = workbooks[name]["frame"]
    bad = [str(c) for c in frame.columns if _PLACEHOLDER.match(str(c))]
    assert not bad, (
        f"{name}: the upload path resolved placeholder column name(s) {bad}; "
        f"all columns = {[str(c) for c in frame.columns]}; "
        f"the file's real columns = {workbooks[name]['truth'].columns}")


@pytest.mark.parametrize("name", sorted(SPREADSHEET_DATASETS))
def test_the_declared_columns_are_resolved(name, workbooks):
    truth = workbooks[name]["truth"]
    if not truth.columns:
        pytest.skip("no column ground truth declared for this shape")
    frame = workbooks[name]["frame"]
    resolved = [str(c) for c in frame.columns]
    missing = [c for c in truth.columns if c not in resolved]
    assert not missing, (
        f"{name}: {len(missing)} declared column(s) absent: {missing}\n"
        f"  ground truth = {truth.columns}\n"
        f"  resolved     = {resolved}")


@pytest.mark.parametrize("name", sorted(SPREADSHEET_DATASETS))
def test_the_row_count_is_the_tables_row_count(name, workbooks):
    truth = workbooks[name]["truth"]
    if truth.n_rows is None:
        pytest.skip("no row-count ground truth declared for this shape")
    frame = workbooks[name]["frame"]
    assert len(frame) == truth.n_rows, (
        f"{name}: read {len(frame)} rows, the table has {truth.n_rows} "
        f"(difference {len(frame) - truth.n_rows:+d}). Extra rows are usually a "
        "title, a sub-header or a footnote block being read as data.")


@pytest.mark.parametrize("name", sorted(
    n for n, (_, truth) in SPREADSHEET_DATASETS.items() if truth.sheet_name))
def test_the_reader_lands_on_the_sheet_the_answer_is_on(name, workbooks):
    """Sheet choice graded as itself, by name, not inferred from what is missing.

    ``_resolve_sheet`` ranks sheets by row count, so the longest tab wins
    whatever the question was. The test below catches the same defect on the
    10-K by noticing the line items are absent; this one states it directly, so
    a fix that changes which sheet is chosen is distinguishable from a fix that
    changes how a sheet is parsed.
    """
    got = workbooks[name]
    expected = got["truth"].sheet_name
    assert got["sheet"] == expected, (
        f"{name}: the upload path resolved sheet {got['sheet']!r}, but the "
        f"answer is on {expected!r}. Nothing about the resulting frame says so "
        "-- it parses cleanly, with no placeholder column and no missing value.")


def test_a_ten_k_resolves_the_statement_that_was_asked_about(workbooks):
    """The sheet with the most rows is not the sheet the question is about.

    ``ExcelConnector._resolve_sheet`` picks the widest/longest sheet. In a
    ``Financial_Report.xlsx`` the balance sheet is routinely longer than the
    income statement, so a question about revenue or net income is answered
    off the wrong statement -- silently, with a clean-looking frame.
    """
    got = workbooks["sec_financial_report"]
    truth = got["truth"]
    expected_items = truth.planted_answer.get("line_items") or []
    assert expected_items, "the SEC fixture declares no line items to look for"
    label_column = truth.columns[0] if truth.columns else None
    assert label_column in got["frame"].columns, (
        f"the label column {label_column!r} is not in the resolved frame "
        f"{[str(c) for c in got['frame'].columns]} -- sheet picked was "
        f"{got['sheet']!r}")
    labels = {str(v).strip() for v in got["frame"][label_column].dropna()}
    missing = [item for item in expected_items if item not in labels]
    assert not missing, (
        f"the statement's line item(s) {missing} are not in the frame; the "
        f"connector selected sheet {got['sheet']!r}. A 10-K question about the "
        "income statement was answered off a different statement.")


def test_the_planted_figure_is_reachable(workbooks):
    """A 'meaningful answer' means the planted number can actually be computed."""
    got = workbooks["sec_financial_report"]
    planted = got["truth"].planted_answer
    label, period = planted.get("label"), planted.get("period")
    value = planted.get("value")
    assert label and period and value is not None, "the SEC fixture plants no figure"
    frame = got["frame"]
    assert period in frame.columns, (
        f"the period column {period!r} is not in {[str(c) for c in frame.columns]}")
    label_column = got["truth"].columns[0]
    row = frame[frame[label_column].astype(str).str.strip() == label]
    assert not row.empty, f"no row labelled {label!r} in the resolved frame"
    cell = pd.to_numeric(row.iloc[0][period], errors="coerce")
    assert cell == pytest.approx(value, rel=1e-6), (
        f"{label} / {period} read as {row.iloc[0][period]!r} "
        f"(numeric {cell}), planted {value}")
