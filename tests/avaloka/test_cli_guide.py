"""The HTML CLI guide cannot drift from the CLI.

``docs/cli-user-guide.html`` is generated by ``scripts/gen_cli_guide.py`` from
Typer's own help. These tests read the committed page and the live command
tree and fail when a command or an option exists in one and not the other,
when the page's version is not the package's, or when a worked example names a
flag its command does not accept. The fix is always the same:

    PYTHONPATH=. python scripts/gen_cli_guide.py
"""

from __future__ import annotations

import importlib.util
import re
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[2]
GUIDE = REPO / "docs" / "cli-user-guide.html"
REGEN = "regenerate with: PYTHONPATH=. python scripts/gen_cli_guide.py"


@pytest.fixture(scope="module")
def gen():
    spec = importlib.util.spec_from_file_location("gen_cli_guide", REPO / "scripts" / "gen_cli_guide.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@pytest.fixture(scope="module")
def tree(gen):
    return gen.command_tree()


@pytest.fixture(scope="module")
def page():
    assert GUIDE.exists(), f"{GUIDE} is missing; {REGEN}"
    return GUIDE.read_text(encoding="utf-8")


def _section(page: str, anchor: str) -> str:
    m = re.search(rf"<section id={re.escape(anchor)}>(.*?)</section>", page, re.S)
    assert m, f"the guide has no section for #{anchor}; {REGEN}"
    return m.group(1)


def test_every_command_has_a_section_and_every_section_is_a_command(gen, tree, page):
    commands = {c["path"] for c in tree if c["path"] != "avaloka"}
    assert commands, "the CLI exposes no commands?"
    for path in commands:
        _section(page, gen.anchor(path))
    documented = set(re.findall(r"<section id=cmd-([\w-]+)>", page))
    assert documented == {gen.anchor(p)[4:] for p in commands}, (
        f"guide sections {sorted(documented)} != CLI commands {sorted(commands)}; {REGEN}")


def test_every_option_of_every_command_is_in_its_section(gen, tree, page):
    missing = []
    for cmd in tree:
        anchor = "start" if cmd["path"] == "avaloka" else gen.anchor(cmd["path"])
        section = _section(page, anchor)
        for opt in cmd["options"]:
            for flag in opt["opts"]:
                if f"<code>{flag}</code>" not in section:
                    missing.append(f"{cmd['path']} {flag}")
        for arg in cmd["arguments"]:
            if f"<code>{arg['name']}</code>" not in section:
                missing.append(f"{cmd['path']} <{arg['name']}>")
    assert not missing, f"in the CLI but not in the guide: {missing}; {REGEN}"


def test_no_option_in_the_guide_is_missing_from_the_cli(gen, tree, page):
    """The other direction: a flag removed from the CLI must leave the page."""
    names = gen.option_names(tree)
    stale = []
    for cmd in tree:
        if cmd["path"] == "avaloka":
            continue
        section = _section(page, gen.anchor(cmd["path"]))
        table = section.split("<div class=example>")[0]  # the generated table, not the prose
        for flag in re.findall(r"<code>(--?[a-zA-Z][\w-]*)</code>", table):
            if flag not in names[cmd["path"]]:
                stale.append(f"{cmd['path']} {flag}")
    assert not stale, f"in the guide but not in the CLI: {stale}; {REGEN}"


def test_the_guide_carries_the_package_version(page):
    from avaloka.version import __version__

    m = re.search(r'<meta name="avaloka-version" content="([^"]+)">', page)
    assert m and m.group(1) == __version__, (
        f"guide says {m and m.group(1)!r}, package says {__version__!r}; {REGEN}")


def test_the_worked_examples_only_use_flags_their_command_accepts(gen, tree):
    gen.check_examples(tree)  # exits non-zero on a stale example
    assert set(gen.EXAMPLES) == {c["path"] for c in tree if c["path"] != "avaloka"}


def test_the_format_list_matches_the_loader_when_it_publishes_one(gen, page):
    from avaloka.io import loader

    listed = {suffix for _, suffixes, _ in gen.FORMATS for suffix in suffixes.split()}
    supported = getattr(loader, "SUPPORTED_SUFFIXES", None)
    if supported is not None:
        assert set(supported) == listed, f"FORMATS in scripts/gen_cli_guide.py is stale; {REGEN}"
    section = _section(page, "formats")
    for suffix in listed:
        assert suffix in section, f"{suffix} is not in the guide; {REGEN}"
    assert "part files" in section


def test_the_guide_is_one_self_contained_file_that_fits_a_phone(page):
    assert 'name="viewport" content="width=device-width' in page
    assert "<script" not in page and 'rel="stylesheet"' not in page
    assert "overflow-x:auto" in page and "pre-wrap" in page
    assert "<link" not in page


def test_the_transcript_is_the_narrators_and_names_the_cap(page):
    from avaloka.swarm_limits import grant, limits_for

    section = _section(page, "narration")
    assert "› Avaloka took the brief:" in section
    assert "← sampling specialist" in section and "Avaloka merged the 2 results" in section
    oss = limits_for("oss", has_commercial_build=False)
    assert grant(5, None, oss).message in _section(page, "swarm-size").replace("&#x27;", "'")


def test_the_docs_index_links_the_guide():
    index = (REPO / "docs" / "index.html").read_text(encoding="utf-8")
    assert 'href="cli-user-guide.html"' in index
